'use client'

import { useCallback, useEffect, useRef, useState } from 'react'
import { useParams, useSearchParams } from 'next/navigation'
import Link from 'next/link'
import { browserClient } from '@/lib/supabase'
import { Product, Listing, channels, money, productSchema } from '@/lib/product'
import { photoUrls } from '@/lib/photos'
import { deleteLocalProduct, localListings, localMode, localProduct, saveLocalListing, saveLocalProduct } from '@/lib/local-store'

type Step = 'review' | 'select' | 'export'
type ChannelId = typeof channels[number]['id']
const defaultSelection: Record<ChannelId, boolean> = { facebook: true, olx: true, mercado_livre: true }

export default function ProductEditor() {
  const { id } = useParams<{ id: string }>()
  const search = useSearchParams()
  const autoGenerated = useRef(false)
  const [product, setProduct] = useState<Product | null>(null)
  const [listings, setListings] = useState<Listing[]>([])
  const [images, setImages] = useState<string[]>([])
  const [title, setTitle] = useState('')
  const [description, setDescription] = useState('')
  const [price, setPrice] = useState('')
  const [uncertain, setUncertain] = useState<string[]>([])
  const [step, setStep] = useState<Step>(search.get('etapa') === 'canais' ? 'select' : 'review')
  const [selected, setSelected] = useState(defaultSelection)
  const [busy, setBusy] = useState(false)
  const [generating, setGenerating] = useState(false)
  const [error, setError] = useState('')
  const [message, setMessage] = useState('')

  const load = useCallback(async () => {
    if (localMode) {
      const item = localProduct(id)
      if (!item) throw new Error('Anúncio não encontrado.')
      setProduct(item)
      setTitle(item.title)
      setDescription(item.description)
      setPrice((item.price_cents / 100).toFixed(2))
      setImages(item.photo_paths)
      setListings(localListings(id))
      return
    }
    const db = browserClient()
    const { data, error } = await db.from('products').select('*').eq('id', id).single()
    if (error) throw error
    const item = data as Product
    setProduct(item)
    setTitle(item.title)
    setDescription(item.description)
    setPrice((item.price_cents / 100).toFixed(2))
    setImages(await photoUrls(item.photo_paths || []))
    const result = await db.from('channel_listings').select('*').eq('product_id', id)
    if (result.error) throw result.error
    setListings(result.data as Listing[])
  }, [id])

  useEffect(() => { load().catch(e => setError(e.message)) }, [load])

  const generate = useCallback(async () => {
    setError(''); setMessage(''); setGenerating(true)
    try {
      const response = await fetch(`/api/products/${id}/generate`, { method: 'POST' })
      const data = await response.json()
      if (!response.ok) throw new Error(data.error || 'Falha ao gerar')
      setTitle(data.title)
      setDescription(data.description)
      setUncertain(data.uncertain)
      setProduct(current => current ? { ...current, title: data.title, description: data.description } : current)
      setMessage('Rascunho gerado. Revise todos os detalhes antes de publicar.')
    } catch (e) {
      setError(e instanceof Error ? e.message : 'Não conseguimos gerar agora.')
    } finally { setGenerating(false) }
  }, [id])

  useEffect(() => {
    if (product && search.get('gerar') === '1' && !autoGenerated.current) {
      autoGenerated.current = true
      void generate()
    }
  }, [product, search, generate])

  async function save(advance = false) {
    if (!product) return
    setError(''); setMessage('')
    const cents = Math.round(Number(price.replace(',', '.')) * 100)
    const parsed = productSchema.safeParse({ title, description, price_cents: cents, category: product.category, condition: product.condition })
    if (!parsed.success) { setError('Confira o título, a descrição e o preço.'); return }
    if (advance && !description.trim()) { setError('Escreva uma descrição antes de escolher os canais.'); return }
    setBusy(true)
    try {
      const updated = { ...product, ...parsed.data, updated_at: new Date().toISOString() }
      if (localMode) saveLocalProduct(updated)
      else {
        const { error } = await browserClient().from('products').update({ ...parsed.data, updated_at: updated.updated_at }).eq('id', id)
        if (error) throw error
      }
      setProduct(updated)
      if (advance) setStep('select')
      else setMessage('Alterações salvas.')
    } catch (e) { setError(e instanceof Error ? e.message : 'Não foi possível salvar.') }
    finally { setBusy(false) }
  }

  function prepareSelected() {
    if (!Object.values(selected).some(Boolean)) { setError('Escolha pelo menos um marketplace.'); return }
    setError(''); setMessage(''); setStep('export')
  }

  async function mark(channel: ChannelId, url: string | null) {
    setError(''); setMessage('')
    if (url) {
      try {
        const address = new URL(url)
        const domains: Record<ChannelId, string[]> = {
          facebook: ['facebook.com', 'www.facebook.com'],
          olx: ['olx.com.br', 'www.olx.com.br'],
          mercado_livre: ['mercadolivre.com.br', 'www.mercadolivre.com.br'],
        }
        if (address.protocol !== 'https:' || !domains[channel].includes(address.hostname)) throw new Error()
      } catch { setError('Informe um link HTTPS válido do marketplace selecionado.'); return }
    }
    if (localMode) {
      saveLocalListing({ id: crypto.randomUUID(), product_id: id, channel, status: 'publicado', external_url: url })
      setListings(localListings(id))
      if (product) { const updated = { ...product, status: 'publicado' as const }; saveLocalProduct(updated); setProduct(updated) }
    } else {
      const db = browserClient()
      const { data: { user } } = await db.auth.getUser()
      if (!user) { setError('Entre na sua conta para continuar.'); return }
      const { error } = await db.from('channel_listings').upsert({
        user_id: user.id, product_id: id, channel, status: 'publicado', external_url: url, confirmed_at: new Date().toISOString(),
      }, { onConflict: 'product_id,channel' })
      if (error) { setError(error.message); return }
      const result = await db.from('channel_listings').select('*').eq('product_id', id)
      setListings((result.data || []) as Listing[])
      await db.from('products').update({ status: 'publicado' }).eq('id', id)
      setProduct(current => current ? { ...current, status: 'publicado' } : current)
    }
    setMessage('Você marcou este anúncio como publicado.')
  }

  async function copy(value: string, label: string) {
    try { await navigator.clipboard.writeText(value); setMessage(`${label} copiado.`) }
    catch { setError('Não foi possível copiar. Selecione e copie o texto no editor.') }
  }

  async function downloadPhotos() {
    if (!product) return
    setError('')
    for (let index = 0; index < product.photo_paths.length; index++) {
      let url: string
      if (localMode) url = product.photo_paths[index]
      else {
        const { data, error } = await browserClient().storage.from('product-photos').download(product.photo_paths[index])
        if (error) { setError('Não foi possível baixar uma das fotos.'); return }
        url = URL.createObjectURL(data)
      }
      const anchor = document.createElement('a')
      anchor.href = url
      anchor.download = `${product.title.replace(/[^a-z0-9]/gi, '-').slice(0, 40)}-${index + 1}.jpg`
      anchor.click()
      if (!localMode) setTimeout(() => URL.revokeObjectURL(url), 10000)
    }
    setMessage('Fotos prontas para baixar.')
  }

  async function sold() {
    if (!product) return
    if (localMode) { const updated = { ...product, status: 'vendido' as const }; saveLocalProduct(updated); setProduct(updated) }
    else {
      const { error } = await browserClient().from('products').update({ status: 'vendido' }).eq('id', id)
      if (error) { setError(error.message); return }
      setProduct({ ...product, status: 'vendido' })
    }
    setMessage('Produto marcado como vendido.')
  }

  async function remove() {
    if (!product || !window.confirm('Excluir este anúncio e suas fotos?')) return
    if (localMode) { deleteLocalProduct(id); location.href = '/app'; return }
    setBusy(true)
    const db = browserClient()
    if (product.photo_paths.length) await db.storage.from('product-photos').remove(product.photo_paths)
    const { error } = await db.from('products').delete().eq('id', id)
    if (error) { setError(error.message); setBusy(false) }
    else location.href = '/app'
  }

  if (!product) return <><Link href="/app" className="text-link">← Meus anúncios</Link><p role="status" style={{ marginTop: 30 }}>{error || 'Carregando anúncio…'}</p></>

  const selectedChannels = channels.filter(channel => selected[channel.id])
  return <>
    <Link href="/app" className="text-link">← Meus anúncios</Link>
    <div className="wizard-header">
      <div className="wizard-steps" aria-label="Progresso do anúncio">
        <span className="done">1 · Produto</span><span className={step === 'review' ? 'current' : 'done'}>2 · Revisão</span><span className={step !== 'review' ? 'current' : ''}>3 · Canais</span>
      </div>
      <h1 className="page-title">{step === 'review' ? 'Revise seu anúncio' : step === 'select' ? 'Onde você quer vender?' : 'Anúncio pronto para levar'}</h1>
      <p className="lead">{step === 'review' ? 'Confira os detalhes antes de escolher os canais.' : step === 'select' ? 'Ative os marketplaces desejados. Você finaliza a publicação em cada site.' : 'Use os dados abaixo em cada marketplace selecionado.'}</p>
    </div>

    {step === 'review' && <div className="editor-layout">
      <aside><div className="card">{images.length ? <><div className="product-thumb" style={{ borderRadius: 14, overflow: 'hidden' }}><img src={images[0]} alt={product.title}/></div><div className="photo-grid">{images.slice(1).map((url, index) => <div className="photo-tile" key={url}><img src={url} alt={`Foto ${index + 2} de ${product.title}`}/></div>)}</div></> : <div className="product-thumb">Sem fotos</div>}<p className="subtle">{product.category} · {product.condition}</p><strong>{money(product.price_cents)}</strong></div></aside>
      <section className="card"><div className="field"><label htmlFor="title">Título</label><input id="title" maxLength={100} value={title} onChange={event => setTitle(event.target.value)}/></div><div className="field"><label htmlFor="description">Descrição</label><textarea id="description" value={description} maxLength={4000} onChange={event => setDescription(event.target.value)} style={{ minHeight: 230 }}/></div><div className="field"><label htmlFor="price">Preço (R$)</label><input id="price" type="number" min="1" step="0.01" inputMode="decimal" value={price} onChange={event => setPrice(event.target.value)}/></div>{uncertain.length > 0 && <div className="notice warning"><strong>Confira estes detalhes:</strong><ul>{uncertain.map((item, index) => <li key={index}>{item}</li>)}</ul></div>}<div className="actions"><button className="btn" onClick={() => save(true)} disabled={busy || generating}>{busy ? 'Salvando…' : 'Salvar e escolher canais →'}</button><button className="btn secondary" onClick={() => save()} disabled={busy || generating}>Salvar rascunho</button>{!localMode && <button className="btn secondary" onClick={generate} disabled={generating}>{generating ? 'Preparando anúncio…' : 'Gerar com IA'}</button>}</div></section>
    </div>}

    {step === 'select' && <section className="channel-picker" aria-label="Escolher marketplaces">
      <div className="selection-intro"><div><span className="eyebrow">Escolha seus canais</span><h2>Selecione onde anunciar</h2><p>Você pode preparar um ou vários canais com os mesmos dados.</p></div><span className="selection-count">{selectedChannels.length} de 3 selecionados</span></div>
      <div className="channel-switch-list">{channels.map((channel, index) => <button key={channel.id} type="button" className={`channel-switch-row ${selected[channel.id] ? 'is-selected' : ''}`} role="switch" aria-checked={selected[channel.id]} aria-label={`${channel.name}: ${selected[channel.id] ? 'selecionado' : 'não selecionado'}`} onClick={() => setSelected(current => ({ ...current, [channel.id]: !current[channel.id] }))}><span className={`channel-symbol channel-${channel.id}`} aria-hidden="true">{index === 0 ? 'f' : index === 1 ? 'O' : 'M'}</span><span className="channel-switch-copy"><strong>{channel.name}</strong><small>Preparar e abrir · publicação manual</small></span><span className="switch-track" aria-hidden="true"><span className="switch-thumb"/></span></button>)}</div>
      <div className="selection-footer"><button className="btn secondary" onClick={() => setStep('review')}>← Voltar à revisão</button><button className="btn" onClick={prepareSelected} disabled={selectedChannels.length === 0}>Preparar para {selectedChannels.length} {selectedChannels.length === 1 ? 'canal' : 'canais'} →</button></div>
      <p className="subtle">Selecionar um canal não publica o anúncio. Você poderá copiar os dados e concluir no site correspondente.</p>
    </section>}

    {step === 'export' && <><div className="export-summary card"><div className="export-summary-photo">{images[0] ? <img src={images[0]} alt={product.title}/> : <span>▧</span>}</div><div><span className="eyebrow">Seu produto</span><h2>{product.title}</h2><strong>{money(product.price_cents)}</strong><p>{selectedChannels.length} {selectedChannels.length === 1 ? 'canal selecionado' : 'canais selecionados'}</p></div></div><div className="channel-list">{selectedChannels.map(channel => <ChannelExportCard key={channel.id} id={channel.id} name={channel.name} url={channel.url} listing={listings.find(item => item.channel === channel.id)} onCopyTitle={() => copy(title, 'Título')} onCopyDescription={() => copy(description, 'Descrição')} onDownload={downloadPhotos} hasPhotos={product.photo_paths.length > 0} onMark={url => mark(channel.id, url)}/>)}</div><div className="selection-footer"><button className="btn secondary" onClick={() => setStep('select')}>← Alterar canais</button><Link className="btn secondary" href="/app">Voltar aos anúncios</Link></div></>}

    {error && <p className="error" role="alert">{error}</p>}
    {message && <p className="notice" role="status">{message}</p>}
    <hr className="divider"/>
    <div className="actions"><button className="btn secondary" onClick={sold} disabled={product.status === 'vendido'}>Marcar produto como vendido</button><button className="btn danger" onClick={remove} disabled={busy}>Excluir anúncio</button></div>
  </>
}

function ChannelExportCard({ id, name, url, listing, onCopyTitle, onCopyDescription, onDownload, hasPhotos, onMark }: { id: ChannelId; name: string; url: string; listing?: Listing; onCopyTitle: () => void; onCopyDescription: () => void; onDownload: () => void; hasPhotos: boolean; onMark: (url: string | null) => void }) {
  const [link, setLink] = useState(listing?.external_url || '')
  useEffect(() => setLink(listing?.external_url || ''), [listing?.external_url])
  return <section className="card export-card"><div className="export-card-head"><span className={`channel-symbol channel-${id}`} aria-hidden="true">{id === 'facebook' ? 'f' : id === 'olx' ? 'O' : 'M'}</span><div><h3>{name}</h3><span className="badge">Preparar e abrir</span></div></div><p>Copie os dados, baixe as fotos e finalize no site do marketplace.</p><div className="actions"><button className="btn small secondary" onClick={onCopyTitle}>Copiar título</button><button className="btn small secondary" onClick={onCopyDescription}>Copiar descrição</button>{hasPhotos && <button className="btn small secondary" onClick={onDownload}>Baixar fotos</button>}<a className="btn small" href={url} target="_blank" rel="noopener noreferrer">Abrir {name} ↗</a></div><div className="field" style={{ margin: '18px 0 8px' }}><label htmlFor={`link-${id}`}>Link do anúncio publicado (opcional)</label><input id={`link-${id}`} type="url" placeholder="https://..." value={link} onChange={event => setLink(event.target.value)}/></div><button className="text-link plain-button" onClick={() => onMark(link || null)}>Marcar como publicado por mim</button>{listing?.status === 'publicado' && <p className="confirmed">Confirmado por você{listing.external_url && <> · <a href={listing.external_url} target="_blank" rel="noopener noreferrer">Ver anúncio</a></>}</p>}</section>
}
